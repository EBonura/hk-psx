/// The family of one action type, or "other" when unmapped.
pub fn family(action: &str) -> &'static str {
    match MAP.binary_search_by(|(k, _)| (*k).cmp(action)) {
        Ok(i) => MAP[i].1,
        Err(_) => "other",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn map_is_sorted_unique_and_uses_known_families() {
        assert!(MAP.windows(2).all(|w| w[0].0 < w[1].0), "MAP must be sorted and unique for binary search");
        assert!(MAP.iter().all(|(_, f)| FAMILIES.contains(f)));
        assert_eq!(family("Wait"), "timers");
        assert_eq!(family("NoSuchAction"), "other");
    }
}

/// Every action type the family map names (the census vocabulary), in name order.
pub fn all_types() -> impl Iterator<Item = &'static str> {
    MAP.iter().map(|(k, _)| *k)
}
