"""The Toll Machines' table for game/src/toll.rs (data/toll.rs).

A `Toll Machine` (host/world_links.py `toll_record`) is an UP-to-inspect Yes/No box that takes Geo and
opens every Toll Gate of its scene. The cook of the bit, the gates and the persistence is the links'; this
writes what the guest's module needs to run the box: per machine its scene, its range box (the trigger
collider the hero body has to be inside, Q16 world units), its prompt marker, its price (the `Prices` sheet
row its `Price String Name` names) and the bit that opens the gates (`scene_id * 128 + state_index`, the
id `world::State` keeps), plus the question the box asks (the `Prompts` sheet row its `Prompt Convo`
names, broken into lines the way the dialogue panel breaks it) and the wait between Yes and the bit.

Not reproduced: the `Take Control` walk to the machine, the hero's `Box_up` and `Box_disappear` clips, the
machine's own open animation, the sound of the coin.

    .venv/bin/python host/tolls.py
"""
import hashlib, json
from source import ROOT, Source, dump
from npc_dialogue import font_advances, _pages, MAX_PAGES, _quote

OUTPUT = ROOT / 'data/toll.rs'
REPORT = ROOT / '.hkpsx/toll.json'
LABEL = 'Inspect'
BREAKABLES_PER_SCENE = 128


def q16(value):
    return round(value * 65536)


def cook():
    report = json.loads((ROOT / 'data/regions.json').read_text())
    advances = font_advances(Source())
    rows = []
    questions = set()
    waits = set()
    for link in report['links']:
        if link.get('family') != 'Toll Machine':
            continue
        waits.add(link['hit_delay_ticks'])
        for machine in link['toll']['machines']:
            questions.add(machine['question'])
            x0, y0, x1, y1 = (q16(v) for v in machine['box'])
            rows.append((link['scene_id'], link['scene_name'], [x0, y0, x1, y1],
                         [q16(machine['marker'][0]), q16(machine['marker'][1])], machine['price'],
                         link['scene_id'] * BREAKABLES_PER_SCENE + link['state_index'], machine['source']))
    if len(questions) > 1 or len(waits) > 1:
        raise ValueError(f'toll machines disagree: {sorted(questions)} / {sorted(waits)}')
    question = next(iter(questions), '')
    lines = [line for page in _pages(question, advances) for line in page] if question else []
    if len(lines) > 4:
        raise ValueError(f'the toll question needs {len(lines)} lines')
    out = ['// Generated by host/tolls.py from the local Windows source; no retail payload is embedded.',
           'pub struct Machine {',
           '    pub scene: usize,',
           '    pub bounds: [i32; 4],',
           '    pub marker: [i32; 2],',
           '    pub price: u32,',
           '    /// The scene state id (`scene * 128 + state`) of the bit that removes the scene\'s Toll Gates.',
           '    pub id: usize,',
           '}',
           f'pub const TOLL_WAIT: u16 = {next(iter(waits), 0)};',
           f'pub const TOLL_LABEL: &str = {_quote(LABEL)};',
           f'pub static QUESTION: &[&str] = &[{",".join(_quote(line) for line in lines)}];',
           'pub static MACHINES: &[Machine] = &[']
    for scene, _name, bounds, marker, price, state, _source in rows:
        out.append(f'    Machine {{ scene: {scene}, bounds: {bounds}, marker: {marker}, price: {price}, id: {state} }},')
    out.append('];')
    OUTPUT.write_text('\n'.join(out) + '\n')
    dump(REPORT, {'format': 'HKTOLL01', 'machines': [
        {'scene': name, 'source': source, 'price': price, 'id': state, 'box': bounds}
        for _scene, name, bounds, _marker, price, state, source in rows],
        'question': question, 'lines': lines, 'wait_ticks': sorted(waits),
        'sha256': hashlib.sha256(OUTPUT.read_bytes()).hexdigest()})
    print(f'Toll machines: {len(rows)} in {len({r[0] for r in rows})} scenes, {len(lines)} question lines', flush=True)


if __name__ == '__main__':
    cook()
