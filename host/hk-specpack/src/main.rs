//! `hk-specpack <root> <source fnv>`: pack the spec statics compiled in from
//! `$HK_SPECPACK_SRC/scene_actors.rs` (`SCENE_ACTORS`, by catalogue scene id) into
//! `<root>/data/scene-specs/scene_<id>.hkspec` and `<root>/data/scene_specs.rs`.
use hk_sim::runner::Attack;
use hk_sim::wire::{self, NO_CORPSE};
use hk_sim::{ActorController, ActorSpec, CorpseSpec};
use std::fmt::Write as _;
use std::path::PathBuf;

include!(concat!(env!("HK_SPECPACK_SRC"), "/scene_actors.rs"));

const SECTOR: usize = 2048;
/// Pool ceilings: the guest holds one scene's specs and corpses in BSS (game/src/spec_pool.rs), so
/// a scene past these fails the cook rather than the boot. Raise them knowingly: each spec is 108
/// bytes of resident memory, each corpse 48.
const POOL_SPECS_CAP: usize = 24;
const POOL_CORPSES_CAP: usize = 24;

type Result<T> = std::result::Result<T, String>;

fn main() {
    if let Err(e) = run() {
        eprintln!("hk-specpack: {e}");
        std::process::exit(1);
    }
}

/// The runner audio family a scene plays: 1 none, 2 Zombie (false), 3 Mossman (true), the codes
/// game/src/disc.rs `runner_family` has always used.
fn runner_family(specs: &[ActorSpec]) -> u8 {
    specs
        .iter()
        .find_map(|s| match s.controller {
            ActorController::Runner { params, .. } => Some(if params.attack == Attack::SwipeCalm { 3 } else { 2 }),
            ActorController::ZombieShield { .. } => Some(2),
            _ => None,
        })
        .unwrap_or(1)
}

fn run() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    let root = PathBuf::from(args.get(1).ok_or("usage: hk-specpack <root> <source fnv>")?);
    let source_fnv: u32 = args.get(2).and_then(|s| s.parse().ok()).ok_or("source fnv")?;
    let out_dir = root.join("data/scene-specs");
    std::fs::create_dir_all(&out_dir).map_err(|e| e.to_string())?;
    for old in std::fs::read_dir(&out_dir).map_err(|e| e.to_string())? {
        std::fs::remove_file(old.map_err(|e| e.to_string())?.path()).map_err(|e| e.to_string())?;
    }
    let scenes = SCENE_ACTORS.len();
    let mut bodies: Vec<Vec<u8>> = Vec::new();
    let (mut max_specs, mut max_corpses, mut max_bytes) = (0usize, 0usize, 0usize);
    let mut family = Vec::new();
    let mut false_knight = None;
    for (id, specs) in SCENE_ACTORS.iter().enumerate() {
        // Equal corpses share one record, as the linker's merge of equal constants did.
        let mut corpses: Vec<&CorpseSpec> = Vec::new();
        let mut keys: Vec<String> = Vec::new();
        let mut refs: Vec<(&ActorSpec, u8)> = Vec::new();
        for spec in specs.iter() {
            let index = match spec.corpse {
                None => NO_CORPSE,
                Some(c) => {
                    let key = format!("{c:?}");
                    let at = match keys.iter().position(|k| *k == key) {
                        Some(at) => at,
                        None => {
                            keys.push(key);
                            corpses.push(c);
                            corpses.len() - 1
                        }
                    };
                    at as u8
                }
            };
            refs.push((spec, index));
        }
        if specs.len() > POOL_SPECS_CAP || corpses.len() > POOL_CORPSES_CAP {
            return Err(format!(
                "scene {id} has {} specs and {} corpses; the guest pool holds {POOL_SPECS_CAP} and {POOL_CORPSES_CAP}",
                specs.len(),
                corpses.len()
            ));
        }
        let mut buf = vec![0u8; 16 * SECTOR];
        let len = wire::encode_chunk(id as u32, &refs, &corpses, &mut buf)
            .ok_or_else(|| format!("scene {id}: spec chunk does not fit 16 sectors"))?;
        buf.truncate(len);
        max_specs = max_specs.max(specs.len());
        max_corpses = max_corpses.max(corpses.len());
        max_bytes = max_bytes.max(len);
        bodies.push(buf);
        family.push(runner_family(specs));
        if specs
            .iter()
            .any(|s| matches!(s.controller, ActorController::FalseKnight { .. }))
        {
            if false_knight.replace(id).is_some() {
                return Err("two scenes place the False Knight".into());
            }
        }
    }
    let sectors = max_bytes.div_ceil(SECTOR).max(1);
    for (id, mut body) in bodies.into_iter().enumerate() {
        body.resize(sectors * SECTOR, 0);
        std::fs::write(out_dir.join(format!("scene_{id}.hkspec")), body).map_err(|e| e.to_string())?;
    }
    let mut rs = String::new();
    writeln!(rs, "// Generated by host/hk-specpack from the spec statics of data/regions.rs. Do not edit.").unwrap();
    writeln!(rs, "/// Sectors every scene's spec chunk takes on the disc (the widest scene's, padded).").unwrap();
    writeln!(rs, "pub const SPEC_SECTORS: usize = {sectors};").unwrap();
    writeln!(rs, "/// Most specs and corpses one scene holds: the guest pool's size.").unwrap();
    writeln!(rs, "pub const MAX_SCENE_SPECS: usize = {};", max_specs.max(1)).unwrap();
    writeln!(rs, "pub const MAX_SCENE_CORPSES: usize = {};", max_corpses.max(1)).unwrap();
    writeln!(rs, "/// FNV-1a of the spec statics these chunks were packed from (host/hk-build refuses a disc whose").unwrap();
    writeln!(rs, "/// regions.rs specs no longer hash to it: a bind after this step would change a spec unseen).").unwrap();
    writeln!(rs, "pub const SPEC_SOURCE_FNV: u32 = {source_fnv};").unwrap();
    writeln!(rs, "/// The catalogue scene that places the False Knight (usize::MAX: none).").unwrap();
    writeln!(rs, "pub const FALSE_KNIGHT_SCENE: usize = {};", false_knight.map_or("usize::MAX".to_string(), |s| s.to_string())).unwrap();
    writeln!(rs, "/// Runner audio family by catalogue scene id: 1 none, 2 Zombie, 3 Mossman.").unwrap();
    writeln!(rs, "pub static SCENE_RUNNER_FAMILY: [u8; {scenes}] = {family:?};").unwrap();
    std::fs::write(root.join("data/scene_specs.rs"), rs).map_err(|e| e.to_string())?;
    println!(
        "hk-specpack: {scenes} scenes, {sectors} sector(s) each, at most {max_specs} specs and {max_corpses} corpses, widest chunk {max_bytes} bytes"
    );
    Ok(())
}

/// The equivalence proof (docs/SCENE-SPECS.md): every chunk on disk decodes, field by field, to the
/// spec the cook generated, for every scene. Run by `cargo hk-build build` after the pack, so a
/// change to the wire form, the packer or the spec text cannot pass unseen.
#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    fn text_const(name: &str) -> usize {
        let text = std::fs::read_to_string(root().join("data/scene_specs.rs")).unwrap();
        text.lines()
            .find_map(|l| l.strip_prefix(&format!("pub const {name}: usize = ")))
            .map(|v| v.trim_end_matches(';').to_string())
            .map(|v| if v == "usize::MAX" { usize::MAX } else { v.parse().unwrap() })
            .unwrap_or_else(|| panic!("{name} missing"))
    }

    #[test]
    fn every_chunk_decodes_to_the_generated_specs() {
        let sectors = text_const("SPEC_SECTORS");
        let (mut total, mut max_specs, mut max_corpses) = (0, 0, 0);
        for (id, specs) in SCENE_ACTORS.iter().enumerate() {
            let bytes = std::fs::read(root().join(format!("data/scene-specs/scene_{id}.hkspec"))).unwrap();
            assert_eq!(bytes.len(), sectors * SECTOR, "scene {id}: chunk length");
            let corpses: &'static mut [CorpseSpec] = Box::leak(vec![decode_blank(); 24].into_boxed_slice());
            let mut pool = vec![blank_spec(); 24];
            let head = wire::decode_chunk(&bytes, corpses, &mut pool)
                .unwrap_or_else(|| panic!("scene {id}: chunk does not decode"));
            assert_eq!(head.scene_id as usize, id);
            assert_eq!(head.specs, specs.len(), "scene {id}: spec count");
            for (n, (want, got)) in specs.iter().zip(&pool).enumerate() {
                assert_eq!(format!("{want:?}"), format!("{got:?}"), "scene {id} spec {n}");
                // A corpse reference lands in the decoded corpse list, never in the source statics.
                if let (Some(a), Some(b)) = (want.corpse, got.corpse) {
                    assert!(!std::ptr::eq(a, b));
                }
            }
            total += head.specs;
            max_specs = max_specs.max(head.specs);
            max_corpses = max_corpses.max(head.corpses);
            // Anything past the frame is zero padding.
            assert!(bytes[wire::CHUNK_HEAD + head.payload + 4..].iter().all(|&b| b == 0));
        }
        assert_eq!(total, SCENE_ACTORS.iter().map(|s| s.len()).sum::<usize>());
        assert_eq!(max_specs.max(1), text_const("MAX_SCENE_SPECS"));
        assert_eq!(max_corpses.max(1), text_const("MAX_SCENE_CORPSES"));
    }

    #[test]
    fn the_cooked_constants_match_the_specs() {
        let text = std::fs::read_to_string(root().join("data/scene_specs.rs")).unwrap();
        let family: Vec<u8> = SCENE_ACTORS.iter().map(|s| runner_family(s)).collect();
        assert!(text.contains(&format!("pub static SCENE_RUNNER_FAMILY: [u8; {}] = {family:?};", family.len())));
        let fk = SCENE_ACTORS
            .iter()
            .position(|s| s.iter().any(|x| matches!(x.controller, ActorController::FalseKnight { .. })));
        assert_eq!(text_const("FALSE_KNIGHT_SCENE"), fk.unwrap_or(usize::MAX));
    }

    fn decode_blank() -> CorpseSpec {
        wire::decode_corpse(&mut wire::Reader::new(&[0u8; wire::CORPSE_BYTES]))
    }

    fn blank_spec() -> ActorSpec {
        *SCENE_ACTORS.iter().flat_map(|s| s.iter()).next().expect("a spec")
    }
}
