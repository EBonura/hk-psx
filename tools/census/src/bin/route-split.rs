//! Turn an open-loop route tape into a state-driven psoxide-gate journey.
//!
//!   route-split --tape T.pxtape --csv baseline/route.csv --map game.map --out DIR --name N
//!               --disc PATH.cue [--symbols MAP_OF_THE_DISC_UNDER_TEST] [--card FIXTURE.mcd] [--pin SYMBOL=VALUE]...
//!
//! The baseline run (replay_cue.py on the same tape) says where every scene load began and ended
//! (HK_GAME_MODE == 2). The tape is cut at those loads into one segment per stretch of play. The
//! journey plays each segment as a rebased tape, keeps its last held buttons down until the guest
//! reports the load has begun, then waits for HK_SCENE_LOADS and HK_GAME_MODE instead of counting
//! polls through the load. A load that takes longer or shorter moves nothing after it.
//! Output: DIR/NAME.toml plus DIR/NAME-segN.pxtape. Pins become a final ram assert each.
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

const BUTTONS: [(&str, u16); 16] = [
    ("select", 1), ("l3", 2), ("r3", 4), ("start", 8), ("up", 16), ("right", 32), ("down", 64),
    ("left", 128), ("l2", 256), ("r2", 512), ("l1", 1024), ("r1", 2048), ("triangle", 4096),
    ("circle", 8192), ("cross", 16384), ("square", 32768),
];

fn args() -> Result<BTreeMap<String, Vec<String>>, String> {
    let mut m: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut it = std::env::args().skip(1);
    while let Some(k) = it.next() {
        let k = k.strip_prefix("--").ok_or("expected --option")?.to_string();
        m.entry(k).or_default().push(it.next().ok_or("option without value")?);
    }
    Ok(m)
}

fn symbols(map: &str) -> BTreeMap<String, u32> {
    map.lines()
        .filter_map(|l| {
            let f: Vec<&str> = l.split_whitespace().collect();
            (f.len() == 5).then(|| u32::from_str_radix(f[0], 16).ok().map(|a| (f[4].to_string(), a)))?
        })
        .collect()
}

struct Load {
    start: usize,
    end: usize,
    loads_after: u64,
}

fn run() -> Result<(), String> {
    let a = args()?;
    let one = |k: &str| -> Result<&String, String> {
        a.get(k).and_then(|v| v.first()).ok_or_else(|| format!("missing --{k}"))
    };
    let tape = std::fs::read(one("tape")?).map_err(|e| e.to_string())?;
    if tape.len() < 16 || &tape[..8] != b"PXITAPE2" {
        return Err("not a PXITAPE2 tape".into());
    }
    let count = u32::from_le_bytes(tape[8..12].try_into().unwrap()) as usize;
    if tape.len() != 16 + count * 6 {
        return Err("tape length does not match its header".into());
    }
    let rows: Vec<&[u8]> = tape[16..].chunks(6).collect();
    let mask = |i: usize| u16::from_le_bytes([rows[i][0], rows[i][1]]);

    let syms = symbols(&std::fs::read_to_string(one("map")?).map_err(|e| e.to_string())?);
    let col = |name: &str| format!("ram_{:x}", syms.get(name).copied().unwrap_or(0));
    let text = std::fs::read_to_string(one("csv")?).map_err(|e| e.to_string())?;
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().ok_or("empty csv")?.split(',').collect();
    let at = |n: &str| header.iter().position(|h| *h == n).ok_or_else(|| format!("csv has no column {n}"));
    let (c_polls, c_mode, c_loads) = (at("port1_polls")?, at(&col("HK_GAME_MODE"))?, at(&col("HK_SCENE_LOADS"))?);

    // Spans of HK_GAME_MODE == 2, in polls.
    let mut spans: Vec<Load> = Vec::new();
    let mut open: Option<usize> = None;
    for line in lines {
        let f: Vec<&str> = line.split(',').collect();
        let (polls, mode, loads): (usize, u64, u64) =
            (f[c_polls].parse().unwrap_or(0), f[c_mode].parse().unwrap_or(0), f[c_loads].parse().unwrap_or(0));
        match (open, mode) {
            (None, 2) => open = Some(polls),
            (Some(s), m) if m != 2 => {
                spans.push(Load { start: s, end: polls, loads_after: loads });
                open = None;
            }
            _ => {}
        }
    }
    if spans.is_empty() {
        return Err("the baseline run has no scene load".into());
    }

    let out = PathBuf::from(one("out")?);
    std::fs::create_dir_all(&out).map_err(|e| e.to_string())?;
    let name = one("name")?;
    let mut toml = String::new();
    let _ = writeln!(toml, "# Generated by route-split from {} and the baseline {}.", one("tape")?, one("csv")?);
    let _ = writeln!(toml, "name = \"{name}\"\ntitle = \"{name} (state-driven)\"");
    let _ = writeln!(toml, "disc = [\"{}\"]\nsymbols = [\"{}\"]\nmax_ticks = 2000000", one("disc")?, one("symbols").unwrap_or(one("map")?));
    if let Some(card) = a.get("card").and_then(|v| v.first()) {
        use sha2::{Digest, Sha256};
        let bytes = std::fs::read(card).map_err(|e| format!("{card}: {e}"))?;
        let sha: String = Sha256::digest(&bytes).iter().map(|b| format!("{b:02x}")).collect();
        let _ = writeln!(toml, "card_fixture = {{ path = \"{card}\", sha256 = \"{sha}\" }}");
    }
    let seg_names = |k: usize| format!("{name}-seg{k}.pxtape");
    let mut pieces: Vec<(usize, usize)> = spans.iter().scan(0usize, |p, s| { let r = (*p, s.start); *p = s.end; Some(r) }).collect();
    pieces.push((spans.last().unwrap().end, count));
    for (k, &(lo, hi)) in pieces.iter().enumerate() {
        let hi = hi.min(count);
        let lo = lo.min(hi);
        let mut seg = b"PXITAPE2".to_vec();
        seg.extend_from_slice(&((hi - lo) as u32).to_le_bytes());
        seg.extend_from_slice(&0u32.to_le_bytes());
        for r in &rows[lo..hi] {
            seg.extend_from_slice(r);
        }
        std::fs::write(out.join(seg_names(k)), seg).map_err(|e| e.to_string())?;
        let _ = writeln!(toml, "\n[[step]]\nlabel = \"play stretch {k} (polls {lo}..{hi} of the baseline)\"\ntape = \"{}\"", seg_names(k));
        if k > 0 {
            let _ = writeln!(toml, "tape_rebase = true");
        }
        // A tape step is capped at 3600 ticks unless it says otherwise.
        let _ = writeln!(toml, "timeout = {}", (hi - lo) + 1200);
        if k < spans.len() {
            let held = if hi > lo { mask(hi - 1) } else { 0 };
            let names: Vec<String> = BUTTONS.iter().filter(|(_, m)| held & m != 0).map(|(n, _)| format!("\"{n}\"")).collect();
            if !names.is_empty() {
                // The stretch ends mid-walk: keep the last buttons down until the load has begun.
                let _ = writeln!(toml, "\n[[step]]\nlabel = \"keep walking until load {k} begins\"\npress = [{}]\ntimeout = 1200", names.join(", "));
                let _ = writeln!(toml, "[step.hold_until]\nkind = \"ram\"\nsym = \"HK_GAME_MODE\"\nop = \"eq\"\nvalue = 2");
            }
            let _ = writeln!(toml, "\n[[step]]\nlabel = \"wait for scene load {k} to be admitted\"\ntimeout = 3600");
            let _ = writeln!(toml, "[step.wait_until]\nkind = \"ram\"\nsym = \"HK_SCENE_LOADS\"\nop = \"ge\"\nvalue = {}", spans[k].loads_after);
            let _ = writeln!(toml, "\n[[step]]\nlabel = \"wait for gameplay\"\ntimeout = 3600");
            let _ = writeln!(toml, "[step.wait_until]\nkind = \"ram\"\nsym = \"HK_GAME_MODE\"\nop = \"eq\"\nvalue = 1");
        }
    }
    let pins = a.get("pin").cloned().unwrap_or_default();
    if !pins.is_empty() {
        let _ = writeln!(toml, "\n[[step]]\nlabel = \"the route's end-state pins\"\ncheckpoint = \"end\"\ngolden = false\nno_matrix = true");
        for p in pins {
            let (s, v) = p.split_once('=').ok_or("--pin SYMBOL=VALUE")?;
            let _ = writeln!(toml, "[[step.assert]]\nkind = \"ram\"\nsym = \"{s}\"\nop = \"eq\"\nvalue = {v}\nnote = \"{s}\"");
        }
    }
    std::fs::write(out.join(format!("{name}.toml")), toml).map_err(|e| e.to_string())?;
    println!("{} loads, {} stretches -> {}", spans.len(), pieces.len(), out.display());
    Ok(())
}

fn main() {
    if let Err(e) = run() {
        eprintln!("route-split: {e}");
        std::process::exit(1);
    }
}
