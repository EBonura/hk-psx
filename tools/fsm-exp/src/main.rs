//! FSM v2 truth-pass experiments (docs/FSM-V2-DESIGN.md step 0, E1 and E2).
//!
//! 1. Family dispatch cost: a direct call, a `jalr` through a 14-word entry table (the
//!    design's FAMILY_ENTRY), a 14-arm `match` (the fallback) and a two-level table
//!    (family, then op), in cycles per dispatch read from root counter 1.
//! 2. The kernel on a real bank (Hornet 1) with stub handlers: actions run and cycles per tick.
//! The kernel's and the handlers' byte counts come from the link map, not from this program.
#![no_std]
#![no_main]
#![allow(static_mut_refs)]

extern crate psx_rt;

mod arity {
    // Generated by `fsm3-sizes` from the original data: not committed.
    include!(env!("FSM_EXP_ARITY"));
}
mod families;
mod kernel;

use core::hint::black_box;
use psx_rt::tty;

#[repr(C, align(4))]
struct Aligned<const N: usize>([u8; N]);
// The Hornet 1 bank written by `fsm3-sizes` (cooked from the original data: not committed).
static HORNET: Aligned<{ include_bytes!(env!("FSM_EXP_BANK")).len() }> = Aligned(*include_bytes!(env!("FSM_EXP_BANK")));

fn clock_start() {
    psx_io::timers::set_mode(psx_io::timers::Timer::Timer1, 0);
}
#[inline(always)]
fn clock() -> u16 {
    psx_io::timers::counter(psx_io::timers::Timer::Timer1)
}

fn dec(label: &str, v: u32) {
    tty::print(label);
    let mut buf = [0u8; 10];
    let mut n = 0;
    let mut x = v;
    if x == 0 {
        buf[0] = b'0';
        n = 1;
    }
    while x > 0 {
        buf[n] = b'0' + (x % 10) as u8;
        x /= 10;
        n += 1;
    }
    let mut out = [0u8; 10];
    for i in 0..n {
        out[i] = buf[n - 1 - i];
    }
    tty::print(core::str::from_utf8(&out[..n]).unwrap());
    tty::println("");
}

// ---- E1: dispatch variants ----------------------------------------------------------------

static mut SINK: u32 = 0;
const N: usize = 512;
static IDX: [u8; 16] = [0, 5, 10, 1, 6, 11, 2, 7, 12, 3, 8, 13, 4, 9, 0, 5];

macro_rules! fam_fns {
    ($($name:ident = $k:expr),*) => {$(
        #[inline(never)]
        unsafe extern "C" fn $name(c: &mut kernel::Ctx, op: u8) -> u16 {
            let _ = op;
            c.index = c.index.wrapping_add($k);
            if c.flags & 1 != 0 { 0 } else { 1 }
        }
    )*};
}
fam_fns!(f0 = 1, f1 = 2, f2 = 3, f3 = 4, f4 = 5, f5 = 6, f6 = 7, f7 = 8, f8 = 9, f9 = 10, f10 = 11, f11 = 12, f12 = 13, f13 = 14);

static mut TABLE: [kernel::Handler; 14] = [f0, f1, f2, f3, f4, f5, f6, f7, f8, f9, f10, f11, f12, f13];
// Second level: per family, an op table of 8 handlers (all the same function here).
static mut OPS: [kernel::Handler; 8] = [f0; 8];

#[inline(never)]
unsafe fn via_table(c: &mut kernel::Ctx, n: usize) -> u32 {
    let mut acc = 0u32;
    for i in 0..n {
        let fam = IDX[i & 15] as usize;
        acc = acc.wrapping_add((core::ptr::read_volatile(&raw const TABLE[fam]))(c, i as u8) as u32);
    }
    acc
}
#[inline(never)]
unsafe fn via_match(c: &mut kernel::Ctx, n: usize) -> u32 {
    let mut acc = 0u32;
    for i in 0..n {
        let op = i as u8;
        let r = match IDX[i & 15] {
            0 => f0(c, op),
            1 => f1(c, op),
            2 => f2(c, op),
            3 => f3(c, op),
            4 => f4(c, op),
            5 => f5(c, op),
            6 => f6(c, op),
            7 => f7(c, op),
            8 => f8(c, op),
            9 => f9(c, op),
            10 => f10(c, op),
            11 => f11(c, op),
            12 => f12(c, op),
            _ => f13(c, op),
        };
        acc = acc.wrapping_add(r as u32);
    }
    acc
}
#[inline(never)]
unsafe fn via_two_level(c: &mut kernel::Ctx, n: usize) -> u32 {
    let mut acc = 0u32;
    for i in 0..n {
        let fam = IDX[i & 15] as usize;
        let t = core::ptr::read_volatile(&raw const TABLE[fam]);
        acc = acc.wrapping_add(t(c, i as u8) as u32);
        let o = core::ptr::read_volatile(&raw const OPS[i & 7]);
        acc = acc.wrapping_add(o(c, i as u8) as u32);
    }
    acc
}
#[inline(never)]
unsafe fn via_direct(c: &mut kernel::Ctx, n: usize) -> u32 {
    let mut acc = 0u32;
    for i in 0..n {
        let _ = IDX[i & 15];
        acc = acc.wrapping_add(f3(c, i as u8) as u32);
    }
    acc
}
#[inline(never)]
unsafe fn loop_only(c: &mut kernel::Ctx, n: usize) -> u32 {
    let mut acc = 0u32;
    for i in 0..n {
        let fam = IDX[i & 15] as usize;
        acc = acc.wrapping_add(fam as u32 ^ i as u32);
        c.index = c.index.wrapping_add(1);
    }
    acc
}

unsafe fn measure(c: &mut kernel::Ctx, f: unsafe fn(&mut kernel::Ctx, usize) -> u32) -> u32 {
    let mut best = u32::MAX;
    for _ in 0..7 {
        let a = clock();
        SINK = SINK.wrapping_add(black_box(f(c, black_box(N))));
        let b = clock();
        let d = b.wrapping_sub(a) as u32;
        if d < best {
            best = d;
        }
    }
    best
}

// ---- main ----------------------------------------------------------------------------------

static mut FSMS: [core::mem::MaybeUninit<kernel::Fsm>; 20] = [const { core::mem::MaybeUninit::uninit() }; 20];
static mut ARENA: [u32; 2048] = [0; 2048];
static mut TREE: core::mem::MaybeUninit<kernel::Tree> = core::mem::MaybeUninit::uninit();

#[no_mangle]
fn main() {
    clock_start();
    tty::println("FSMEXP begin");
    unsafe {
        let mut c = kernel::Ctx { t: core::ptr::null_mut(), f: 0, flags: 0, index: 0, enter: false, ops: core::ptr::null() };
        let base = measure(&mut c, loop_only);
        dec("E1 loop_only cycles/512 ", base);
        for (name, f) in [
            ("direct", via_direct as unsafe fn(&mut kernel::Ctx, usize) -> u32),
            ("jalr_table", via_table),
            ("match14", via_match),
            ("two_level", via_two_level),
        ] {
            let t = measure(&mut c, f);
            tty::print("E1 ");
            tty::print(name);
            dec(" cycles/512 ", t);
            dec("   x1000 per dispatch net ", (t.saturating_sub(base)) * 1000 / N as u32);
        }

        // E2: the kernel on the Hornet bank, stub handlers, then the real handlers where written.
        for real in [false, true] {
            if real {
                families::bind();
            }
            core::ptr::write_bytes(ARENA.as_mut_ptr(), 0, ARENA.len());
            let tree = TREE.as_mut_ptr();
            core::ptr::write_bytes(tree, 0, 1);
            kernel::tree_init(&mut *tree, HORNET.0.as_ptr(), FSMS.as_mut_ptr() as *mut kernel::Fsm, ARENA.as_mut_ptr());
            kernel::tree_start(&mut *tree);
            let a = clock();
            let ran0 = (*tree).ran;
            let mut worst = 0u32;
            let mut total = 0u32;
            for _ in 0..300 {
                let t0 = clock();
                kernel::tree_tick(&mut *tree);
                let d = clock().wrapping_sub(t0) as u32;
                total += d;
                if d > worst {
                    worst = d;
                }
            }
            let _ = a;
            tty::print(if real { "E2 real handlers " } else { "E2 stub handlers " });
            dec("actions run in 300 ticks ", (*tree).ran - ran0);
            dec("   cycles per tick (avg) ", total / 300);
            dec("   cycles per tick (worst) ", worst);
            dec("   cycles per action ", total / ((*tree).ran - ran0).max(1));
        }
        dec("E2 sink ", SINK);
    }
    tty::println("FSMEXP end");
    loop {}
}
