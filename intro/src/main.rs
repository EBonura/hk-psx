/// One cooked movie: the root file it lives in and the figures the cook
/// measured for it.
struct Cooked {
    file: &'static str,
    frames: u32,
    width: u16,
    height: u16,
    max_chunks: u16,
    rle_words: usize,
    xa: Option<(u8, u8)>,
    latency_vblanks: u32,
}

/// In the order the source plays them.
const MOVIES: [Cooked; cooked::MOVIES] = [
    Cooked {
        file: "HKINTRO1.STR",
        frames: cooked::prologue::FRAMES,
        width: cooked::prologue::WIDTH,
        height: cooked::prologue::HEIGHT,
        max_chunks: cooked::prologue::MAX_CHUNKS,
        rle_words: cooked::prologue::RLE_WORDS,
        xa: cooked::prologue::XA,
        latency_vblanks: cooked::prologue::LATENCY_VBLANKS,
    },
    Cooked {
        file: "HKINTRO2.STR",
        frames: cooked::intro::FRAMES,
        width: cooked::intro::WIDTH,
        height: cooked::intro::HEIGHT,
        max_chunks: cooked::intro::MAX_CHUNKS,
        rle_words: cooked::intro::RLE_WORDS,
        xa: cooked::intro::XA,
        latency_vblanks: cooked::intro::LATENCY_VBLANKS,
    },
];
/// The disc's boot executable, which is the game.
const GAME_FILE: &str = "PSX.EXE";

/// Where the player's buffers sit: low RAM above the kernel, which the game's
/// image overwrites once the movies are over. They end below this program.
const PLAYER_MEMORY: usize = 0x8004_0000;
/// No sector for two seconds ends the movie.
const STALL_VBLANKS: u32 = 120;

extern "C" {
    /// First byte of this program's image (psoxide.ld).
    static __text_start: u8;
}

fn image_start() -> u32 {
    (&raw const __text_start) as u32
}

/// Where the font's palette sits in VRAM (game/src/dialogue.rs draws every glyph with it).
const FONT_CLUT: (u16, u16) = (320, 481);
/// The letterbox bar under the picture: the movie is 176 lines centred in 240, so the lines
/// from 208 down are black in every display buffer and the player never writes them.
const LETTERBOX_Y: u16 = 208;
const LETTERBOX_H: u16 = 32;
/// The popup of the original (`CinematicSkipPopup`): it fades in over 0.15 s, holds for 2 s and
/// fades out over 1 s. Counted in VBlanks of a 60 Hz display.
const FADE_IN: u32 = 9;
const HOLD: u32 = 120;
const FADE_OUT: u32 = 60;
/// Full brightness of a glyph, as the game draws them (0x80 is the font's colours as they are).
const FULL: u32 = 0x80;

/// "Press any button to skip", shown when a first button is pressed during a movie and drawn into
/// the bars of the player's three display buffers (a flip never rewrites them).
struct Prompt {
    /// The VBlank the prompt began.
    since: Option<u32>,
    /// What the bars hold now (the brightness drawn), or `None` when nothing was drawn yet in
    /// this movie's freshly cleared buffers.
    drawn: Option<u32>,
}

impl Prompt {
    /// A press of any button while the prompt is up skips; one while it is not shows it.
    fn press(&mut self, now: u32) -> bool {
        if self.since.is_some_and(|at| now.wrapping_sub(at) <= FADE_IN + HOLD) {
            return true;
        }
        self.since = Some(now);
        false
    }

    /// The brightness the prompt has at `now`, 0 to [`FULL`].
    fn brightness(&self, now: u32) -> u32 {
        let Some(at) = self.since else { return 0 };
        let t = now.wrapping_sub(at);
        if t < FADE_IN {
            FULL * t / FADE_IN
        } else if t < FADE_IN + HOLD {
            FULL
        } else if t < FADE_IN + HOLD + FADE_OUT {
            FULL * (FADE_IN + HOLD + FADE_OUT - t) / FADE_OUT
        } else {
            0
        }
    }

    /// Bring the bars up to date, unless the player has a VRAM copy in flight (the GPU's port is
    /// then not ours; the next VBlank tries again).
    fn update(&mut self, now: u32) {
        let level = self.brightness(now);
        if self.drawn == Some(level) || (self.drawn.is_none() && level == 0) {
            return;
        }
        if !psx_vram::dma_copy_to_vram_done() {
            return;
        }
        for (x, y) in player::DEFAULT_BUFFERS {
            draw_bar(x, y, level);
        }
        self.drawn = Some(level);
        if level == 0 {
            self.since = None;
        }
    }
}

/// The bar of the display buffer at (`x`, `y`) cleared and, for a non-zero `level`, the prompt
/// centred in it.
fn draw_bar(x: u16, y: u16, level: u32) {
    // The bar black (GP0 fill: always on whole 16-pixel columns, outside the draw area).
    write_command(0x0200_0000);
    write_command(u32::from(y + LETTERBOX_Y) << 16 | u32::from(x));
    write_command(u32::from(LETTERBOX_H) << 16 | 320);
    if level == 0 {
        return;
    }
    // Drawing area and offset of this buffer, no texture window.
    write_command(0xE200_0000);
    write_command(0xE300_0000 | u32::from(x) | u32::from(y + LETTERBOX_Y) << 10);
    write_command(0xE400_0000 | u32::from(x + 319) | u32::from(y + 239) << 10);
    write_command(0xE500_0000 | u32::from(x) | u32::from(y) << 11);
    // The font's page, semi-transparent adding, as the game's text: its palette carries the
    // semi-transparency bit, so a glyph's grey is added to the black bar.
    let page = TexturePage::new(prompt_text::FONT_X, prompt_text::FONT_PAGE_Y, TextureDepth::Bit4).uv_word(1);
    write_command(0xE100_0000 | u32::from(page));
    let clut = u32::from(Clut::new(FONT_CLUT.0, FONT_CLUT.1).uv_word());
    let color = 0x6600_0000 | level * 0x0001_0101;
    let left = (320 - prompt_text::WIDTH) / 2;
    let top = LETTERBOX_Y as i16 + (LETTERBOX_H as i16 - prompt_text::GLYPH_H as i16) / 2;
    for (u, v, dx) in prompt_text::GLYPHS {
        write_command(color);
        write_command(u32::from((left + dx) as u16) | u32::from(top as u16) << 16);
        write_command(u32::from(u) | u32::from(v) << 8 | clut << 16);
        write_command(u32::from(prompt_text::GLYPH_W) | u32::from(prompt_text::GLYPH_H) << 16);
    }
}

/// The pad and the skip prompt it drives.
struct Skip {
    port: ControllerPort,
    /// Buttons down at the poll before; the pad starts out counted as held, so a button still
    /// down from the menu that launched the disc does not count as a press.
    held: u16,
    last_vblank: u32,
    prompt: Prompt,
}

impl Skip {
    /// The player's per-VBlank poll: `true` when the player skips the rest.
    fn poll(&mut self) -> bool {
        // The pad answers once per VBlank at most; the player calls this far
        // more often.
        let now = interrupts::vblank_count();
        if now == self.last_vblank {
            return false;
        }
        self.last_vblank = now;
        let down = psx_pad::poll_on(&mut self.port, Port::One).buttons.bits();
        let pressed = down & !self.held != 0;
        self.held = down;
        if pressed && self.prompt.press(now) {
            return true;
        }
        self.prompt.update(now);
        false
    }

    /// A movie is starting: the player has cleared its buffers.
    fn begin_movie(&mut self) {
        self.prompt.drawn = None;
    }
}

/// Plays one movie and says how it ended.
fn play_movie(skip: &mut Skip, cooked: &Cooked, limit: u32) -> Option<Stop> {
    skip.begin_movie();
    let Some((lba, _)) = player::find_root_file(cooked.file) else {
        tty::println("hk-intro: a movie is missing from this disc");
        return None;
    };
    let movie = Movie {
        lba,
        frames: cooked.frames,
        width: cooked.width,
        height: cooked.height,
        max_chunks: cooked.max_chunks,
        rle_words: cooked.rle_words,
        xa: cooked.xa,
    };
    let config = Config {
        // 15-bit: the picture can be drawn over, and the player leaves the
        // display as it found it.
        depth: Depth::Rgb15,
        buffers: player::DEFAULT_BUFFERS,
        screen_width: 320,
        screen_height: 240,
        // The cook sized the sound's delay for this headroom (hk-intro-cook).
        latency_vblanks: cooked.latency_vblanks,
        stall_vblanks: STALL_VBLANKS,
    };
    let words = player::memory_words(&movie, config.depth);
    if PLAYER_MEMORY + words * 4 > limit as usize {
        tty::println("hk-intro: a movie's buffers would reach the intro's own image");
        return None;
    }
    // SAFETY: low RAM between the kernel's area and this image: nothing lives
    // there until the game is loaded over it, after the player has returned.
    let memory = unsafe { core::slice::from_raw_parts_mut(PLAYER_MEMORY as *mut u32, words) };
    let outcome = player::play(&movie, &config, memory, &mut || skip.poll());
    report(cooked.file, &outcome);
    Some(outcome.stop)
}

fn report(file: &str, o: &player::Outcome) {
    let stop = match o.stop {
        Stop::End => "end",
        Stop::Skipped => "skipped",
        Stop::Stall => "stall",
        Stop::CdError => "cd-error",
        Stop::Wedged => "wedged",
        Stop::Setup => "setup",
    };
    tty::print("INTRO ");
    tty::print(file);
    tty::print(" ");
    tty::print(stop);
    for (label, v) in [
        ("shown", o.shown),
        ("skipped", o.skipped),
        ("late", o.late),
        ("worst_late", o.worst_late_vblanks),
        ("dropped", o.dropped),
        ("errors", o.decode_errors),
        ("last_frame", o.last_frame),
        ("vblanks", o.vblanks),
        ("kcyc_vlc", o.kcyc_vlc),
        ("kcyc_mdec", o.kcyc_mdec),
        ("kcyc_wait", o.kcyc_wait),
    ] {
        tty::print(" ");
        tty::print(label);
        tty::print("=");
        print_decimal(v);
    }
    tty::println("");
}

fn print_decimal(mut v: u32) {
    let mut digits = [0u8; 10];
    let mut at = digits.len();
    loop {
        at -= 1;
        digits[at] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    tty::print(core::str::from_utf8(&digits[at..]).unwrap_or("?"));
}

/// A dim track and a bar over it, at the foot of a black screen, while the
/// game's image streams in.
struct Loading;

const BAR_X: i16 = 80;
const BAR_Y: i16 = 222;
const BAR_W: i16 = 160;
const BAR_H: i16 = 4;
const TRACK: u32 = 0x0030_3030;
const FILL: u32 = 0x00B0_B0B0;

impl Presentation for Loading {
    fn setup(&mut self) {
        paint::setup(319, 239);
    }
    fn begin(&mut self) {
        paint::rect(0, 0, 320, 240, 0);
        paint::rect(BAR_X, BAR_Y, BAR_W, BAR_H, TRACK);
        paint::draw_sync();
        paint::show();
    }
    fn update(&mut self, done: u32, total: u32) {
        let width = (done * BAR_W as u32 / total.max(1)).min(BAR_W as u32) as i16;
        paint::rect(BAR_X, BAR_Y, width, BAR_H, FILL);
        paint::draw_sync();
    }
    fn finish(&mut self) {}
    fn diagnostic_mode(&mut self) {
        paint::diagnostic_mode();
    }
    fn no_scratchpad(&mut self) {}
}

#[no_mangle]
fn main() {
    // Entered from the running game, not from the BIOS: put the machine where
    // the BIOS leaves it (SPU silent, interrupts masked, DMA off, GPU reset).
    // SAFETY: nothing else is running; the game that jumped here is gone.
    unsafe { runtime::quiesce() };
    interrupts::install_vblank_counter();
    let peripherals = Peripherals::take().expect("the intro takes the peripherals once, at boot");
    // The player and the chain loader take the drive, the MDEC and the GPU's
    // channel over themselves, as their docs say; the display and the SPU are
    // set up here.
    let _gpu = Gpu::new(
        peripherals.gpu_dma,
        DisplayConfig::new(VideoMode::Ntsc, Resolution::R320X240),
    );
    let _spu = Spu::new(peripherals.spu_dma);
    spu::set_main_volume(Volume::MAX, Volume::MAX);

    let mut skip = Skip {
        port: peripherals.controller_port,
        held: u16::MAX,
        last_vblank: interrupts::vblank_count(),
        prompt: Prompt { since: None, drawn: None },
    };
    for movie in &MOVIES {
        // A skip ends the whole sequence, as it does in the original, not just
        // the movie that is playing.
        if play_movie(&mut skip, movie, image_start()) != Some(Stop::End) {
            break;
        }
    }

    let Some((lba, _)) = player::find_root_file(GAME_FILE) else {
        tty::println("hk-intro: no PSX.EXE on this disc");
        loop {
            interrupts::wait_vblank();
        }
    };
    // The game is on the same disc as this program, so it takes over the
    // bases the launcher gave this one. Passing zero here made a game read
    // its packs at unshifted sectors whenever the disc is a multi-program one.
    let lba_offset = psx_io::disc_base::lba_offset();
    let cdda_track_base = u32::from(psx_io::disc_base::cdda_track_base());
    // SAFETY: the game's payload ends below this image (the game is linked
    // below the pool this blob sits in), the player has returned, and nothing
    // else uses the drive. `run` never returns. No checksum: the disc builder
    // cannot know the boot executable's, and only the read is trusted.
    unsafe { runtime::run(lba, lba_offset, cdda_track_base, 0, image_start(), Loading) }
}
